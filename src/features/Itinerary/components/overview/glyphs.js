// Which artwork a transport booking gets (Train, Bus, Taxi, Plane, Other).
export const transportGlyph = (method) => {
  const value = String(method || '').toLowerCase();
  if (value.includes('train') || value.includes('rail') || value.includes('metro') || value.includes('subway')) return 'train';
  if (value.includes('bus') || value.includes('coach') || value.includes('shuttle')) return 'bus';
  if (value.includes('taxi') || value.includes('cab') || value.includes('uber') || value.includes('car') || value.includes('ride')) return 'taxi';
  if (value.includes('plane') || value.includes('flight')) return 'flight';
  return 'transport';
};
